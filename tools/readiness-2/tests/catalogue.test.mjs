// Readiness 2.0: the catalogue data is read from the Use-Case Catalogue at build time, not copied by hand.
// Run: node tools/readiness-2/tests/catalogue.test.mjs   (after node tools/readiness-2/build.mjs)
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { root, catalogue, tester } from './load.mjs';
import { catalogueModel } from '../build.mjs';
const { ok, done } = tester('catalogue');
const eq = (a, b) => JSON.stringify(a) === JSON.stringify(b);

const catHtml = readFileSync(join(root, '../use-case-catalogue/index.html'), 'utf8');
const labels = JSON.parse(readFileSync(join(root, '../register/data/uc-labels.json'), 'utf8'));
const fresh = catalogueModel(catHtml, labels), built = catalogue();
const X = JSON.parse(catHtml.match(/<script id="data" type="application\/json">([\s\S]*?)<\/script>/)[1]);

ok(eq(built, fresh), 'index.html carries the catalogue as it is now (rebuild after the catalogue changes)');
ok(eq(fresh.cats.map(c => c.name), ['Commercial', 'Guest-facing', 'Operational', 'Administrative']), 'exactly the four categories, in order');
ok(fresh.cats.every(c => c.line.length > 10), 'each category has the catalogue’s one-line description');
ok(fresh.nDepts === 15 && fresh.depts.length === 15, '15 departments');
ok(fresh.nUses === 99 && fresh.depts.reduce((a, d) => a + d.uses.length, 0) === 99, '99 use cases');
ok(fresh.nDepts === X.depts.length && fresh.nUses === X.depts.reduce((a, d) => a + d.uses.length, 0), 'counts are computed from the catalogue, not fixed');
// ids: '<dept id>-<1-based index>', like the catalogue, the readiness check and the AI Register
X.depts.forEach((d, di) => d.uses.forEach((u, i) => {
  const m = fresh.depts[di].uses[i];
  ok(m.id === d.id + '-' + (i + 1) && m.n === u.n && m.task === u.task && m.use === (u.use || ''), 'use case ' + d.id + '-' + (i + 1) + ' matches the catalogue');
}));
fresh.depts.forEach((d, di) => ok(d.id === X.depts[di].id && d.name === X.depts[di].name && d.cat === X.depts[di].cat, 'department ' + d.id));
const ids = fresh.depts.flatMap(d => d.uses.map(u => u.id));
ok(new Set(ids).size === 99 && ids.every(id => /^[a-z]+-\d+$/.test(id)), 'ids unique and shaped like the #use= contract ([a-z]+-\\d+)');
ok(eq(Object.keys(fresh.depts[0].uses[0]).sort(), ['id', 'n', 'task', 'use']), 'only name, task and use level are carried (no sources copied)');
ok(['High', 'Medium', 'Low', 'Very low'].includes(fresh.depts[0].uses[0].use), 'use level is the catalogue’s rating');
// Department counts per category
const per = c => fresh.depts.filter(d => d.cat === c).length;
ok(per('Commercial') === 3 && per('Guest-facing') === 3 && per('Operational') === 4 && per('Administrative') === 5, 'departments per category (3/3/4/5)');
ok(fresh.depts.find(d => d.id === 'fo').name === 'Front Office' && fresh.depts.find(d => d.id === 'fo').cat === 'Guest-facing', 'Front Office is Guest-facing');

// The hand-over: every use case the readiness check can check is reachable with #use=<id>; the others are flagged
const rc = readFileSync(join(root, '../readiness-check/index.html'), 'utf8');
const rd = JSON.parse(rc.match(/<script type="application\/json" id="d-data">([\s\S]*?)<\/script>/)[1]);
const rcIds = new Set(); rd.cat.depts.forEach(d => d.uses.forEach((u, i) => { if (!u.notTool) rcIds.add(d.id + '-' + (i + 1)); }));
const notTool = fresh.depts.flatMap(d => d.uses.filter(u => u.notTool).map(u => u.id));
ok(eq(notTool, ['lg-4']), 'one entry is a document, not a tool (lg-4), and is flagged');
ok(ids.filter(id => !notTool.includes(id)).every(id => rcIds.has(id)), 'every other use case opens in the readiness check');
ok(!rcIds.has('lg-4'), 'the readiness check indeed has no check for lg-4');

// The page itself
const page = readFileSync(join(root, 'index.html'), 'utf8');
ok(page.includes('<title>Readiness 2.0</title>') && page.includes('GENERATED by tools/readiness-2/build.mjs'), 'built page');
ok(!/\/\*__[A-Z]+__\*\/|<!--__DATA__-->/.test(page), 'no build marker left');
ok(!/wikipedia/i.test(page) && !/AIHA|Hospitality Alliance/i.test(page), 'no Wikipedia, no AIHA');
done();
