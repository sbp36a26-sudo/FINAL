// Builds tools/index.html (the published hub page) from the AI Assessment tool
// plus the hub bar. The Assessment tool must be the main page: saving
// (Claude's built-in storage) only works on an artifact's main page, not in a tab frame.
//
// Run after editing assessment/index.html or hub/hub-bar.html:
//   node tools/build-hub.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const app = readFileSync(join(here, 'assessment/index.html'), 'utf8');
let bar = readFileSync(join(here, 'hub/hub-bar.html'), 'utf8');

/* Cache-busting (v2.6, 24 Nov 2026): a short content hash of each frame tool's page. The hub loads '<page>?v=<hash>', so after a
   publish the browser never shows a stale tool from its cache. Rebuild the tools first, then this hub. */
export const PAGES = { 'use-case-catalogue': 'use-case-catalogue/index.html', 'readiness-2': 'readiness-2/index.html', 'ai-act-guide': 'ai-act-guide/index.html', register: 'register/index.html', team: 'readiness-check/team.html' };
export function hashes(root) { return Object.fromEntries(Object.entries(PAGES).map(([t, p]) => [t, createHash('sha256').update(readFileSync(join(root, p))).digest('hex').slice(0, 10)])); }
const MARK = '{} /*__HUB_VER__*/';
if (!bar.includes(MARK)) throw new Error('hub/hub-bar.html: missing ' + MARK);
bar = bar.replace(MARK, () => JSON.stringify(hashes(here)) + ' /* written by build-hub.mjs */');

if (!app.includes('<body>')) throw new Error('assessment/index.html has no <body> tag');
let out = app
  .replace('<title>AI Assessment Tool</title>', '<title>HFTP Tool Hub</title>')
  // The hub page sits one folder up, so point the tool's own files at assessment/.
  .replace('src="engine.js"', 'src="assessment/engine.js"')
  .replace('src="report.js"', 'src="assessment/report.js"')
  .replace('src="flows.js"', 'src="assessment/flows.js"')
  .replaceAll("'lib/", "'assessment/lib/")
  .replace('<body>', '<body>\n<!-- GENERATED by tools/build-hub.mjs: edit assessment/index.html or hub/hub-bar.html instead -->\n' + bar);
writeFileSync(join(here, 'index.html'), out);
console.log('wrote tools/index.html', JSON.stringify(hashes(here)));
