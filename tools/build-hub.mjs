// Builds tools/index.html (the published hub page) from the AI Assessment tool
// plus the hub bar. The Assessment tool must be the main page: saving
// (Claude's built-in storage) only works on an artifact's main page, not in a tab frame.
//
// Run after editing assessment/index.html or hub/hub-bar.html:
//   node tools/build-hub.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const app = readFileSync(join(here, 'assessment/index.html'), 'utf8');
const bar = readFileSync(join(here, 'hub/hub-bar.html'), 'utf8');

if (!app.includes('<body>')) throw new Error('assessment/index.html has no <body> tag');
let out = app
  .replace('<title>AI Assessment Tool</title>', '<title>HFTP Tool Hub</title>')
  // The hub page sits one folder up, so point the tool's own files at assessment/.
  .replace('src="engine.js"', 'src="assessment/engine.js"')
  .replace('src="report.js"', 'src="assessment/report.js"')
  .replaceAll("'lib/", "'assessment/lib/")
  .replace('<body>', '<body>\n<!-- GENERATED by tools/build-hub.mjs: edit assessment/index.html or hub/hub-bar.html instead -->\n' + bar);
writeFileSync(join(here, 'index.html'), out);
console.log('wrote tools/index.html');
