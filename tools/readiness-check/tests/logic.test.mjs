// Checks the readiness-check scoring rules (v2). Run after building: node tools/readiness-check/tests/logic.test.mjs
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';
const here = dirname(fileURLToPath(import.meta.url)), root = join(here, '..');
const html = readFileSync(join(root, 'index.html'), 'utf8');
const D = JSON.parse(html.match(/<script type="application\/json" id="d-data">([\s\S]*?)<\/script>/)[1]);
const ctx = { self: {} }; vm.runInNewContext(readFileSync(join(root, 'src/logic.js'), 'utf8'), ctx);
const L = ctx.self.RCLogic, M = L.model(D);
let pass = 0, fail = 0; const ok = (c, n) => { if (c) pass++; else { fail++; console.log('FAIL  ' + n); } };
const all = (x, h, v, proof) => { const A = {}, P = {}; L.selectQuestions(M, x, h).forEach(q => { A[q.code] = v; if (q.gate && proof) P[q.code] = 'shown'; }); return [A, P]; };
ok(M.USES.length === 90, '90 tool use cases (the AI-use policy entry is not a tool)');
const x = M.UI['rm-2'], hotel = { type: 'independent' };
let [A, P] = all(x, hotel, 'y', true); let e = L.evaluate(M, x, hotel, A, P);
ok(e.score === 100 && e.level === 'scale', 'all Yes with proof: 100, ready to scale');
[A, P] = all(x, hotel, 'y', false); e = L.evaluate(M, x, hotel, A, P);
ok(e.level === 'found' && e.score <= 39, 'must-have Yes without proof does not pass');
[A, P] = all(x, hotel, 'y', true); L.selectQuestions(M, x, hotel).filter(q => q.gate).forEach(q => A[q.code] = 'u'); e = L.evaluate(M, x, hotel, A, P);
ok(e.level === 'found' && e.score <= 39, 'Not sure on must-haves gives build foundations first');
[A, P] = all(x, hotel, 'p', false); e = L.evaluate(M, x, hotel, A, P);
ok(e.level === 'found', 'must-haves at Partly do not pass');
[A, P] = all(x, hotel, 'y', true); const non = L.selectQuestions(M, x, hotel).filter(q => !q.gate && q.a === 'or'); non.forEach(q => A[q.code] = 'p'); e = L.evaluate(M, x, hotel, A, P);
ok(e.level === 'pilot' && e.score <= 74, 'one area between 40 and 74%: ready to pilot, capped at 74');
[A, P] = all(x, hotel, 'y', true); e = L.evaluate(M, x, hotel, Object.assign({}, A, { [L.selectQuestions(M, x, hotel).find(q => !q.gate).code]: '' }), P);
ok(e.scored.every(r => r.max > 0), 'unanswered questions count as Not sure, not left out');
ok(L.selectQuestions(M, M.UI['rm-2'], hotel).some(q => q.code === 'P5' && q.gate), 'tool acting alone: human override is a must-have');
ok(!L.selectQuestions(M, M.UI['sm-1'], hotel).some(q => q.code === 'T1' && q.gate), 'light tool: two-way data link is not a must-have');
ok(L.selectQuestions(M, M.UI['hr-2'], hotel).some(q => q.code === 'XG' && q.gate), 'staff tool: staff representatives is a must-have');
ok(L.selectQuestions(M, M.UI['gx-2'], hotel).some(q => q.code === 'X2'), 'guest-facing tool: guest acceptance question');
ok(!L.selectQuestions(M, x, { type: 'independent' }).some(q => q.code === 'O3') && L.selectQuestions(M, M.UI['rm-1'], { type: 'managed' }).every(q => q.code !== 'O3' || true), 'managed-only question hidden for independents');
const counts = M.USES.map(u => L.selectQuestions(M, u, hotel).length);
ok(Math.max(...counts) <= 32 && Math.min(...counts) >= 15, 'question count per tool between 15 and 32');
console.log((fail ? 'FAILED' : 'ok') + ': ' + pass + ' passed, ' + fail + ' failed');
process.exit(fail ? 1 : 0);
