// Generates brand/tokens.css from brand.json + decisions.json.
// tokens.css is the ONLY stylesheet allowed to contain raw colours, px sizes or spacing values.
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { ROOT, brand, palette, sections, fontSize, lineHeight, space, contentWidth, columnWidth, tile, kickerTracking } from '../src/brand.js';

const kebab = (s: string) => s.replace(/_/g, '-');
const px = (n: number) => `${n}px`;
const lines: string[] = [];
const v = (name: string, value: string | number, note = '') => lines.push(`  --${name}: ${value};${note ? ` /* ${note} */` : ''}`);

v('font-display', `'${brand.typography.display.family}', sans-serif`);
v('font-body', `'${brand.typography.body.family}', serif`);
v('weight-display', brand.typography.display.weight);
v('weight-body', brand.typography.body.weight);
v('weight-bold', brand.typography.body.bold);
for (const [k, n] of Object.entries(fontSize)) v(`fs-${kebab(k)}`, px(n));
for (const [k, n] of Object.entries(lineHeight)) v(`lh-${kebab(k)}`, px(n));
v('tracking-kicker', kickerTracking);

for (const [k, c] of Object.entries(palette)) v(`color-${k.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase())}`, c);
for (const s of sections) {
  v(`color-${s.cls}`, s.base, s.label);
  v(`color-${s.cls}-fill`, s.fill, `behind white text, ${s.steps.fill} darkening step(s)`);
  v(`color-${s.cls}-text`, s.text, `as text on paper, ${s.steps.text} step(s)`);
  v(`color-${s.cls}-tint`, s.tint, '10% tile');
  v(`color-${s.cls}-text-on-tint`, s.textOnTint, `as text on tile, ${s.steps.textOnTint} step(s)`);
  v(`color-${s.cls}-secondary-on-tint`, s.secondaryOnTint, 'muted, or ink where muted fails AA on the tile');
}

v('u', px(space.u), 'baseline grid unit; all spacing is calc(var(--u) * n)');
v('gutter', px(space.gutter));
v('gap', px(space.gap));
v('margin-inner', px(space.marginInner));
v('margin-outer', px(space.marginOuter));
v('margin-top', px(space.marginTop));
v('content-w', px(contentWidth));
v('content-h', px(space.contentHeight));
v('col-w', px(columnWidth));
v('spread-w', px(space.spreadW));
v('spread-h', px(space.spreadH));
v('page-w', px(space.pageW));
v('page-h', px(space.pageH));
v('tile-pad', px(tile.padding));
v('radius', px(tile.radius));
v('hairline', px(space.hairline), 'thinnest rule (tables, footnote separator)');

let css = `/* GENERATED by scripts/build-tokens.ts from brand/brand.json + brand/decisions.json. Do not edit. */\n:root {\n${lines.join('\n')}\n}\n`;
for (const s of sections) {
  css += `.${s.cls} { --sec: var(--color-${s.cls}); --sec-fill: var(--color-${s.cls}-fill); --sec-text: var(--color-${s.cls}-text); --sec-tint: var(--color-${s.cls}-tint); --sec-text-on-tint: var(--color-${s.cls}-text-on-tint); --sec-secondary-on-tint: var(--color-${s.cls}-secondary-on-tint); }\n`;
}
css += `.sec-0 { --sec: var(--color-primary); --sec-fill: var(--color-primary); --sec-text: var(--color-primary); --sec-tint: var(--color-paper); --sec-text-on-tint: var(--color-primary); --sec-secondary-on-tint: var(--color-muted); } /* contents spread: no section */\n`;
css += `@page { size: ${px(space.spreadW)} ${px(space.spreadH)}; margin: 0; }\n`;
writeFileSync(path.join(ROOT, 'brand/tokens.css'), css);
console.log('brand/tokens.css written');
for (const s of sections) console.log(`  ${s.label}: fill ${s.fill} (+${s.steps.fill}), text ${s.text} (+${s.steps.text}), on tile ${s.textOnTint} (+${s.steps.textOnTint}), tile secondary ${s.secondaryOnTint === palette.muted ? 'muted' : 'ink'}`);
